def _eps_prov(*keys, note=""):
    """Provenance of a Tabulated built from _nk_data entries: computed where k comes from the file; assumed where a
    transparent-range source leaves k = 0 to be assumed."""
    refs = "; ".join(dict.fromkeys(SRC[k]["reference"] for k in keys))
    zero = any(SRC[k]["k"] == "zero" for k in keys)
    ev = "assumed" if zero else "computed"
    n = ("n computed from the measurement; k = 0 assumed in the source's transparent range. " if zero else "") + note
    return P(ev, f"{refs} [{D.DATABASE}, commit {D.COMMIT[:12]}]", CC0, n.strip())


def _uniaxial(o, e):
    return from_source([(SRC[o], 2 / 3), (SRC[e], 1 / 3)])


