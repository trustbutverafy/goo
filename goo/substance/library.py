def _pig(name, eps, eps_prov, d, sg, rho, rho_prov, material, size_prov=None, sep=1e-9, phi0=0.15, surface=None):
    """surface: (gamma, gamma_d, Provenance) of a solid's surface free energy, or None."""
    th = Thermo() if surface is None else Thermo(gamma=surface[0], gamma_d=surface[1])
    extra = {} if surface is None else {"thermo.gamma": surface[2], "thermo.gamma_d": surface[2]}
    return _add(Substance(
        name, eps, Sphere(LogNormal(d, sg)), rho, th, Rheo(separation=sep, phi_percolation=phi0),
        material=material,
        prov=dict(eps=eps_prov, morph=size_prov or P("assumed", note=f"log-normal by volume, d50 {d / um:g} um, "
                                                                     f"sigma_g {sg:g} (classic's sizes)"),
                  rho=rho_prov, reservoir=NONE,
                  **{"rheo.separation": P("assumed", note="closest approach 1 nm: a thin adsorbed layer"),
                     "rheo.phi_percolation": P("assumed", note="YODEL's percolation onset, of order 0.1-0.2")},
                  **extra)))


