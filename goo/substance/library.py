def _n_d_oscillator(n_D, E0=10 * eV):
    """One lossless UV oscillator at E0 whose strength gives index n_D at 589.3 nm (derived, not typed)."""
    E = HC / 589.3e-9
    return Oscillators(1.0, (Lorentz((n_D ** 2 - 1) * (E0 ** 2 - E ** 2) / E0 ** 2, E0, 0.0),))


def _E_eta(eta_a, Ta, eta_b, Tb):
    """Viscous activation energy (J/mol) from viscosities at two temperatures (Arrhenius)."""
    return R_gas * np.log(eta_a / eta_b) / (1 / Ta - 1 / Tb)


