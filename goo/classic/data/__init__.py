"""goo.classic.data: goo's optical data table, as arrays.

`optics.json` holds, per species (pigments, carriers, the acrylic binder, the grounds): its material, its role, a
refractive index spectrum n (and k), Kubelka-Munk K and S spectra per surrounding (oil 1.48, water 1.33, air 1.00;
"bulk" for a continuous medium), S and K against the surrounding's index (`sweep`), and the provenance of every
number at every wavelength: "computed" (Mie theory from CC0 optical constants, cited), "assumed" (a stated physical
assumption), or "guessed" (goo's earlier table, kept because nothing better was found). Sources, method and checks:
classic/docs/OPTICS-DATA.md. The table is regenerated by classic/studies/optics_data.py; nothing here computes optics.

Units: K and S are mm^-1 for the pure pigment (pigment volume fraction 1). goo's classic PIGMENTS are the same
quantity per 0.025 mm of pure pigment: multiply by GOO_UNIT_MM (or ask for units="goo").

    from goo.classic import data
    t = data.load()
    w = t.species("white")
    w.S["oil"]                                   # (42,) mm^-1 on t.wavelength_nm
    data.resample(w.S["oil"], data.GOO_BANDS)    # R, G, B band means and the 1550 nm value
    t.classic_table("oil")                       # {species: {"K": [R, G, B, N], "S": [...]}} in goo units
"""
from __future__ import annotations
import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
import numpy as np

PATH = Path(__file__).with_name("optics.json")
GOO_UNIT_MM = 0.025                                      # classic/SPEC.md section 2: K, S per 0.025 mm of pure pigment
GOO_BANDS = ((600.0, 700.0), (500.0, 600.0), (400.0, 500.0), 1550.0)   # goo's R, G, B (rough) and N
SURROUNDINGS = ("oil", "water", "air")


def _ro(a):
    a = np.array(a, dtype=float); a.flags.writeable = False; return a


@dataclass(frozen=True)
class Species:
    name: str
    role: str                       # "pigment", "carrier", "binder" or "ground"
    material: str
    n: np.ndarray                   # real index on the table's grid
    k: np.ndarray
    K: dict                         # surrounding -> (n_wavelengths,) mm^-1
    S: dict
    provenance: dict                # "n", "k", "K", "S" -> (n_wavelengths,) array of "computed" / "assumed" / "guessed"
    summary: str                    # "computed", "assumed", "guessed" or "mixed"
    sweep_K: np.ndarray | None = None   # (n_media, n_wavelengths) on Table.sweep_n_medium
    sweep_S: np.ndarray | None = None
    size: dict | None = None
    sources: list = field(default_factory=list)
    note: str = ""


class Table:
    """The optical data table: `wavelength_nm`, `names`, `species(name)`, `classic_table()`, `S_in()`."""

    def __init__(self, raw: dict):
        self.raw = raw
        self.wavelength_nm = _ro(raw["wavelength_nm"])
        self.surroundings = dict(raw["surroundings"])
        self.sweep_n_medium = _ro(raw["sweep_n_medium"])
        self.names = tuple(raw["species"])
        self._sp = {}
        for name, r in raw["species"].items():
            pb = r["provenance"]["by_wavelength"]
            sw = r.get("sweep")
            self._sp[name] = Species(
                name=name, role=r["role"], material=r["material"], n=_ro(r["n"]), k=_ro(r["k"]),
                K={s: _ro(v) for s, v in r["K"].items()}, S={s: _ro(v) for s, v in r["S"].items()},
                provenance={q: np.array(v, dtype=object) for q, v in pb.items()}, summary=r["provenance"]["summary"],
                sweep_K=_ro(sw["K"]) if sw else None, sweep_S=_ro(sw["S"]) if sw else None,
                size=r.get("size"), sources=list(r.get("sources", [])), note=r.get("note", ""))

    def species(self, name: str) -> Species:
        return self._sp[name]

    def __contains__(self, name): return name in self._sp
    def __iter__(self): return iter(self.names)

    def by_role(self, role: str):
        return [n for n in self.names if self._sp[n].role == role]

    def S_in(self, name: str, n_medium: float) -> np.ndarray:
        """S spectrum (mm^-1) in a surrounding of any index within the sweep, linear in the index between sweep points."""
        return self._interp_sweep(self._sp[name].sweep_S, n_medium)

    def K_in(self, name: str, n_medium: float) -> np.ndarray:
        return self._interp_sweep(self._sp[name].sweep_K, n_medium)

    def _interp_sweep(self, arr, n_medium):
        if arr is None: raise ValueError("this species has no sweep (it is a continuous medium)")
        nm = self.sweep_n_medium
        if not nm[0] <= n_medium <= nm[-1]: raise ValueError(f"n_medium {n_medium} outside the sweep {nm[0]}..{nm[-1]}")
        j = int(np.clip(np.searchsorted(nm, n_medium) - 1, 0, len(nm) - 2))
        t = (n_medium - nm[j]) / (nm[j + 1] - nm[j])
        return (1 - t) * arr[j] + t * arr[j + 1]

    def bands(self, name: str, quantity: str, surrounding: str = "oil", bands=GOO_BANDS, units: str = "mm"):
        """K or S of one species resampled to bands; units "mm" (mm^-1) or "goo" (per 0.025 mm of pure pigment)."""
        sp = self._sp[name]
        v = resample(getattr(sp, quantity)[surrounding], bands, self.wavelength_nm)
        return v * GOO_UNIT_MM if units == "goo" else v

    def classic_table(self, surrounding: str = "oil", roles=("pigment",)):
        """{species: {"K": [R, G, B, N], "S": [...]}} in goo's units, the shape of goo.classic.engine.PIGMENTS."""
        return {n: {q: self.bands(n, q, surrounding, GOO_BANDS, "goo").tolist() for q in ("K", "S")}
                for n in self.names if self._sp[n].role in roles and surrounding in self._sp[n].K}


def resample(values, bands, wavelength_nm=None):
    """Resample a spectrum on the table's grid to `bands`. Each band is a wavelength (nm: linear interpolation within
    the visible grid, or exactly a grid point such as 1550) or a (lo, hi) interval within the visible grid (the mean
    of the piecewise-linear spectrum over it). Between 780 and 1550 nm there is no data, and asking is an error."""
    w = np.asarray(load().wavelength_nm if wavelength_nm is None else wavelength_nm, float)
    v = np.asarray(values, float)
    vis = w <= 780.0 + 1e-9; wv, vv = w[vis], v[..., vis]
    out = []
    for b in bands:
        if np.ndim(b) == 0:
            b = float(b); hit = np.isclose(w, b)
            if hit.any(): out.append(v[..., int(np.argmax(hit))]); continue
            if not wv[0] <= b <= wv[-1]: raise ValueError(f"{b} nm is outside the table's grid")
            out.append(np.apply_along_axis(lambda y: np.interp(b, wv, y), -1, vv)); continue
        lo, hi = map(float, b)
        if not (wv[0] - 1e-9 <= lo < hi <= wv[-1] + 1e-9): raise ValueError(f"band {b} nm is outside {wv[0]}..{wv[-1]} nm")
        x = np.r_[lo, wv[(wv > lo) & (wv < hi)], hi]
        y = np.apply_along_axis(lambda yy: np.interp(x, wv, yy), -1, vv)
        out.append(np.trapezoid(y, x, axis=-1) / (hi - lo) if hasattr(np, "trapezoid") else np.trapz(y, x, axis=-1) / (hi - lo))
    return np.stack(out, axis=-1)


@lru_cache(maxsize=4)
def _load(path: str) -> Table:
    return Table(json.loads(Path(path).read_text(encoding="utf-8")))


def load(path=None) -> Table:
    """The shipped table (cached), or another file in the same format."""
    return _load(str(PATH if path is None else path))


__all__ = ["load", "resample", "Table", "Species", "GOO_BANDS", "GOO_UNIT_MM", "SURROUNDINGS", "PATH"]
